// Save
async function saveRecord() {
    let isValid = true;

    // ── Item Category ────────────────────────────────────────────────
    const itemCategoryEl = document.getElementById('ddlItemCategory');
    const itemCategoryId = itemCategoryEl.value;
    const itemCategoryError = document.getElementById('errDdlItemCategory');
    if (!itemCategoryId) {
        itemCategoryError.classList.remove('d-none');
        itemCategoryEl.classList.add('is-invalid');
        isValid = false;
    } else {
        itemCategoryError.classList.add('d-none');
        itemCategoryEl.classList.remove('is-invalid');
    }

    // ── Item Name ────────────────────────────────────────────────────
    const nameEl = document.getElementById('txtName');
    const name = nameEl.value.trim();
    const nameError = document.getElementById('nameError');
    if (!name) {
        nameError.classList.remove('d-none');
        nameEl.classList.add('is-invalid');
        isValid = false;
    } else {
        nameError.classList.add('d-none');
        nameEl.classList.remove('is-invalid');
    }

    // ── Unit (required + must be a valid number) ────────────────────
    const unitEl = document.getElementById('txtUnit');
    const unit = unitEl.value.trim();
    const unitError = document.getElementById('unitError');
    if (!unit) {
        unitError.textContent = 'Unit is required.';
        unitError.classList.remove('d-none');
        unitEl.classList.add('is-invalid');
        isValid = false;
    } else if (!/^\d+(\.\d+)?$/.test(unit)) {
        unitError.textContent = 'Please enter a valid unit number.';
        unitError.classList.remove('d-none');
        unitEl.classList.add('is-invalid');
        isValid = false;
    } else {
        unitError.classList.add('d-none');
        unitEl.classList.remove('is-invalid');
    }

    if (!isValid) return;

    // ── Build payload & save ────────────────────────────────────────
    const desc = document.getElementById('txtDescription').value.trim() || null;
    const isActive = document.getElementById('chkIsActive').checked;
    const id = document.getElementById('recordId').value || 0;
    const companyID = document.getElementById('hdnCompanyID').value || 0;
    const sessionID = document.getElementById('hdnSessionID').value || 0;
    const isEdit = id > 0;
    const data = {
        ItemId: id,
        ItemCategoryId: itemCategoryId,
        ItemName: name,
        Unit: unit,
        Description: desc,
        isActive: isActive,
        companyID: companyID,
        sessionID: sessionID
    };

    const r = await fetch('/InventoryItem/Save', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(data)
    });
    const res = await r.json();
    if (res.success) {
        Swal.fire({
            icon: 'success',
            title: 'Saved!',
            text: isEdit
                ? 'Item has been updated successfully.'
                : 'Item has been added successfully.',
            confirmButtonText: 'OK',
            customClass: { confirmButton: 'btn btn-success' },
            buttonsStyling: false
        }).then(() => {
            window.location.href = '/InventoryItem/Index';
        });
    } else {
        Swal.fire({
            icon: 'error',
            title: 'Error',
            text: res.message || 'Failed to save item.',
            confirmButtonText: 'OK',
            customClass: { confirmButton: 'btn btn-danger' },
            buttonsStyling: false
        });
    }
}
async function toggleStatus(id, isActive, checkboxEl) {
    if (!permCanEdit) {
        IV.setNotice('classPageNotice', 'You do not have permission to change status.');
        if (checkboxEl) checkboxEl.checked = !isActive;
        location.reload();
        return;
    }

    // ✅ collect both ids AND the actual checkbox elements
    let sectionIds = [];
    let checkedBoxes = [];
    $('.student-checkbox:checked').each(function () {
        sectionIds.push(parseInt($(this).val()));
        checkedBoxes.push(this);
    });

    // single-row toggle (checkboxEl passed from the row switch)
    if (sectionIds.length === 0) {
        if (id != 0) {
            sectionIds.push(parseInt(id));
            if (checkboxEl) checkedBoxes.push(checkboxEl);
        } else {
            showToast('Please select at least one user', false);
            return;
        }
    }

    const request = {
        ids: sectionIds.join(','),
        isActive: isActive
    };

    // helper to revert every affected checkbox
    function revertAll() {
        checkedBoxes.forEach(cb => { cb.checked = !isActive; });
    }

    try {
        const config = isActive
            ? { icon: 'question', title: 'Activate Record(s)?', text: 'Activating this record will make it visible and available for use across the system. Do you want to continue?', confirmText: 'Yes, Activate', confirmBtnClass: 'btn btn-success me-2', successTitle: 'Activated Successfully!', successText: 'The selected record(s) have been activated and are now available for use.' }
            : { icon: 'warning', title: 'Deactivate Record(s)?', text: 'Deactivating this record will hide it from the system and prevent it from being used. Do you want to continue?', confirmText: 'Yes, Deactivate', confirmBtnClass: 'btn btn-danger me-2', successTitle: 'Deactivated Successfully!', successText: 'The selected record(s) have been deactivated and are no longer available for use.' };

        Swal.fire({
            icon: config.icon,
            title: config.title,
            text: config.text,
            showCancelButton: true,
            confirmButtonColor: '#d33',
            cancelButtonColor: '#3085d6',
            confirmButtonText: 'Yes, proceed!',
            customClass: { confirmButton: 'btn btn-danger me-2', cancelButton: 'btn btn-secondary' },
            buttonsStyling: false
        }).then((result) => {
            if (result.isConfirmed) {
                $.ajax({
                    url: '/InventoryItem/ToggleStatus',
                    type: 'POST',
                    contentType: 'application/json',
                    data: JSON.stringify(request),
                    success: function (res) {
                        if (res.success) {
                            Swal.fire('Updated!', res.message || 'Status updated successfully.', 'success')
                                .then(() => submitForm());
                        } else {
                            revertAll();
                            Swal.fire('Error!', res.message || 'Failed to update status.', 'error');
                        }
                    },
                    error: function (xhr) {
                        revertAll();
                        console.error('Status update error:', xhr.status, xhr.responseText);
                        Swal.fire('Error!', 'An unexpected error occurred.', 'error');
                    }
                });
            } else {
                // ✅ Cancel clicked — revert whatever was toggled
                revertAll();
            }
        });
    }
    catch (err) {
        revertAll();
        console.error(err);
        IV.setNotice('sectionPageNotice', 'Could not update status.');
        location.reload();
    }
}


